"""Embed scripts/ida_ttd.py in the plugin as src/plugin/ida_ttd_module.hh.

The plugin registers the module with IDAPython when it loads, so
`import ida_ttd` works without installing anything. Run this after editing
scripts/ida_ttd.py; the header is committed, so building needs no Python.
The source goes in as base64 lines: a C++ string literal cannot hold it
whole (MSVC caps one at about 16 KB), and base64 needs no escaping.
"""
import base64
import os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(root, "scripts", "ida_ttd.py"), "rb").read()
b64 = base64.b64encode(src).decode("ascii")
lines = [b64[i:i + 100] for i in range(0, len(b64), 100)]

out = []
out.append("// Generated by msbuild/gen_python_module.py from scripts/ida_ttd.py; do not edit.")
out.append("#pragma once")
out.append("")
out.append("namespace idattd")
out.append("{")
out.append("    // The ida_ttd Python module's source, base64.")
out.append("    static const char IDA_TTD_MODULE_B64[] =")
for i, l in enumerate(lines):
    out.append('        "%s"%s' % (l, ";" if i == len(lines) - 1 else ""))
out.append("}")
open(os.path.join(root, "src", "plugin", "ida_ttd_module.hh"), "w", newline="\r\n").write("\n".join(out) + "\n")
print("wrote src/plugin/ida_ttd_module.hh: %d bytes of source" % len(src))
